/**
 * The advisor's vocabulary mirrors `@postgear/seo-engine`'s `SeoRecommendation`
 * rather than importing it: this package must stay free of the engine (which
 * drives a headless browser), and the API is where the two shapes meet.
 */
export type SeoAdviceSeverity = 'critical' | 'warning' | 'info';

export const SEO_ADVICE_SEVERITIES: readonly SeoAdviceSeverity[] = [
  'critical',
  'warning',
  'info',
] as const;

export type SeoAdviceCategory = 'onPage' | 'technical' | 'content' | 'backlink';

export const SEO_ADVICE_CATEGORIES: readonly SeoAdviceCategory[] = [
  'onPage',
  'technical',
  'content',
  'backlink',
] as const;

export type SeoAdviceImpact = 'high' | 'medium' | 'low';

export const SEO_ADVICE_IMPACTS: readonly SeoAdviceImpact[] = ['high', 'medium', 'low'] as const;

/** One rule-based finding the evaluators produced, as the model is shown it. */
export interface SeoAdviceFinding {
  id: string;
  severity: SeoAdviceSeverity;
  category: SeoAdviceCategory;
  title: string;
  issue: string;
  fix: string;
  impact: SeoAdviceImpact;
  /** The evaluator check this finding came from, when there is one. */
  checkId: string | null;
  docsUrl: string | null;
}

export interface SeoAdviceRequest {
  url: string;
  /** 0–100. */
  overall: number;
  grade: string;
  /** The audit in prose, from the engine's `summariseForAdvice`. */
  digest: string;
  /** The rule-based findings; the model prioritises and rewrites them, it does not replace them. */
  findings: SeoAdviceFinding[];
}

export interface SeoAdviceRecommendation {
  id: string;
  severity: SeoAdviceSeverity;
  category: SeoAdviceCategory;
  title: string;
  /** What is wrong and why it matters. */
  issue: string;
  /** What to change, concretely. */
  fix: string;
  impact: SeoAdviceImpact;
  /** A `checkId` from the request's findings, or null: the advisor never invents one. */
  checkId: string | null;
  docsUrl: string | null;
}

export interface SeoAdviceOutput {
  summary: string;
  /** Sorted critical → warning → info, de-duplicated by id, at most twelve. */
  recommendations: SeoAdviceRecommendation[];
}

export interface SeoAdvisor {
  /**
   * One structured model call. Rejects with an {@link AiProviderError}; an
   * abort surfaces as kind `aborted`.
   */
  advise(request: SeoAdviceRequest, options?: { signal?: AbortSignal }): Promise<SeoAdviceOutput>;
}

// ---------------------------------------------------------------------------
// The model seam
// ---------------------------------------------------------------------------

export interface ModelToolCall {
  id: string;
  name: string;
  input: unknown;
}

export interface ModelMessage {
  role: 'system' | 'user' | 'assistant' | 'tool';
  content: string;
  /** Set on an assistant message that asked for tools. */
  toolCalls?: ModelToolCall[];
  /** Set on a tool message: which call this answers. */
  toolCallId?: string;
  /** Set on a tool message: the tool's name. */
  name?: string;
}

export interface ModelToolSpec {
  name: string;
  description: string;
  inputSchema: z.ZodType;
}

export type ModelChunk =
  | { type: 'text'; text: string }
  /** Emitted once, after the text, when the model decided to call tools. */
  | { type: 'tool_calls'; calls: ModelToolCall[] };

/**
 * The one interface between the engine and a language model.
 *
 * `structured` asks for a value matching a schema (the pipeline's stages);
 * `chat` streams a reply that may end in tool calls (the copilot). An
 * implementation is responsible for timeouts, retries and turning provider
 * errors into {@link AiProviderError}.
 */
export interface ModelClient {
  /** "openai:gpt-4.1-mini", "simulation" — reported by `/ai/status`. */
  readonly name: string;
  structured<T>(params: {
    schema: z.ZodType<T>;
    system: string;
    user: string;
    signal?: AbortSignal;
  }): Promise<T>;
  chat(params: {
    messages: ModelMessage[];
    tools: ModelToolSpec[];
    signal?: AbortSignal;
  }): AsyncIterable<ModelChunk>;
}

// ---------------------------------------------------------------------------
// Errors
// ---------------------------------------------------------------------------

export type AiErrorKind =
  /** No model client could be built — no key and no simulation. */
  | 'not_configured'
  /** The provider rejected the key. A deployment problem, not a user one. */
  | 'invalid_key'
  /** 429 after retries. */
  | 'rate_limited'
  /** 5xx or network failure after retries. */
  | 'unavailable'
  | 'timeout'
  /** The model's output did not fit the schema, even after one repair attempt. */
  | 'bad_output'
  /** The provider refused the prompt. The user can rephrase. */
  | 'content_policy'
  | 'aborted';

export class AiProviderError extends Error {
  constructor(
    readonly kind: AiErrorKind,
    message: string,
    /** Whether trying again, unchanged, could reasonably succeed. */
    readonly retryable: boolean,
    options?: { cause?: unknown },
  ) {
    super(message, options);
    this.name = 'AiProviderError';
  }
}

export function isAiProviderError(error: unknown): error is AiProviderError {
  return error instanceof AiProviderError;
}

