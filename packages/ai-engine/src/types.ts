/**
 * The AI engine's contract — every type the API (and the engine's own tests)
 * program against.
 *
 * ## Three seams, all injected
 *
 * The engine never reads an environment variable, opens a database, or stores
 * a file. Three things are handed to it by whoever builds it:
 *
 * - a {@link ModelClient} — the one place a language model is called. The
 *   OpenAI client is the production one; the simulated client produces
 *   deterministic output with no key, so every screen, every credit rule and
 *   every test runs without spending anything (the same reasoning as Sprint 5's
 *   `PUBLISH_SIMULATION`).
 * - a {@link ResearchProvider} — web research (Tavily). Optional: without one
 *   the pipeline skips research and says so, rather than failing.
 * - an {@link ImageGenerator} plus an {@link ImageSink} — DALL-E and the media
 *   library. The engine produces bytes; the API decides where they live.
 *
 * ## Why events, not a return value alone
 *
 * A generation takes tens of seconds. The pipeline reports each stage as it
 * happens through `onEvent`, so the API can stream progress to the browser
 * (SSE) and a person watches research, hook and copy arrive instead of a
 * spinner. The final result is also returned, for callers that do not stream.
 *
 * This file must stay free of runtime imports other than `zod` — it is the
 * contract, and the web app mirrors it in `apps/web/src/types/ai.ts`.
 */
import type { z } from 'zod';

// ---------------------------------------------------------------------------
// Requests
// ---------------------------------------------------------------------------

/** Who is speaking: a person ("I") or a brand ("we"). PRD 5.5 "Tone Adjustment". */
export type Tone = 'personal' | 'company';

export const TONES: readonly Tone[] = ['personal', 'company'] as const;

/** PRD 5.5 "Multi-Format Support": one post or a thread, short or long. */
export type PostFormat = 'one_short' | 'one_long' | 'thread_short' | 'thread_long';

export const POST_FORMATS: readonly PostFormat[] = [
  'one_short',
  'one_long',
  'thread_short',
  'thread_long',
] as const;

export interface GenerateRequest {
  /** What the post should be about — a topic, a brief, a link, a rough draft. */
  topic: string;
  tone: Tone;
  format: PostFormat;
  /** Generate one hero image for the first part. */
  withImage: boolean;
  /**
   * Character ceiling for one part, from the strictest platform selected.
   * Null when the caller has no platform in mind; the format then decides.
   */
  maxCharacters: number | null;
  /**
   * Provider identifiers of the target channels (`x`, `linkedin`, `instagram`…),
   * so the copy can lean into the platform. Empty means "generic".
   */
  platforms: string[];
  /** The workspace's name, used as the brand name in company voice. */
  workspaceName?: string;
}

// ---------------------------------------------------------------------------
// Research
// ---------------------------------------------------------------------------

export interface ResearchSource {
  title: string;
  url: string;
  /** A short excerpt the model was shown — what the UI cites. */
  snippet: string;
}

export interface ResearchProvider {
  /** A human-readable name for logs and status ("tavily", "simulation"). */
  readonly name: string;
  search(query: string, options?: { signal?: AbortSignal }): Promise<ResearchSource[]>;
}

/** The cache a research provider may be wrapped with — the API backs it with Redis. */
export interface ResearchCache {
  get(key: string): Promise<string | null>;
  set(key: string, value: string, ttlSeconds: number): Promise<void>;
}

// ---------------------------------------------------------------------------
// Images
// ---------------------------------------------------------------------------

export interface GeneratedImage {
  data: Buffer;
  mimeType: 'image/png' | 'image/jpeg';
  /** DALL-E rewrites prompts; the rewritten one is kept as the image's alt text. */
  revisedPrompt: string | null;
}

export interface ImageGenerator {
  readonly name: string;
  generate(prompt: string, options?: { signal?: AbortSignal }): Promise<GeneratedImage>;
}

/** What a stored image looks like to the rest of the app: a media library item. */
export interface SavedImage {
  mediaId: string;
  url: string;
  thumbnailUrl: string | null;
}

/** Where generated bytes go. Provided by the API; wraps the media library. */
export interface ImageSink {
  save(image: GeneratedImage, meta: { prompt: string; name: string }): Promise<SavedImage>;
}

// ---------------------------------------------------------------------------
// The content pipeline
// ---------------------------------------------------------------------------

/** The stages of the graph, in order. The UI shows them as a tracker. */
export type GenerateStage = 'research' | 'classify' | 'hook' | 'content' | 'image';

export const GENERATE_STAGES: readonly GenerateStage[] = [
  'research',
  'classify',
  'hook',
  'content',
  'image',
] as const;

export type StageStatus = 'started' | 'done' | 'skipped' | 'failed';

export interface GeneratedPart {
  /** Plain text, with `\n` between lines. No hashtags, no markdown. */
  text: string;
  /** The image prompt the content stage wrote for this part, when images were asked for. */
  imagePrompt: string | null;
  /** The saved hero image. Only ever set on the first part. */
  image: SavedImage | null;
}

export interface GenerateResult {
  tone: Tone;
  format: PostFormat;
  /** One of {@link AI_CATEGORIES}. */
  category: string;
  hook: string;
  parts: GeneratedPart[];
  /** Empty when research was skipped or found nothing. */
  sources: ResearchSource[];
  /** True when a research provider ran and returned sources the model used. */
  researched: boolean;
}

export type GenerateEvent =
  | { type: 'stage'; stage: GenerateStage; status: StageStatus; detail?: string }
  | { type: 'research'; sources: ResearchSource[] }
  | { type: 'category'; category: string }
  | { type: 'hook'; hook: string }
  /** The copy, before any image exists. `image` is null on every part. */
  | { type: 'content'; parts: GeneratedPart[] }
  | { type: 'image'; index: number; image: SavedImage }
  | { type: 'done'; result: GenerateResult };

export interface GenerateOptions {
  signal?: AbortSignal;
  onEvent?: (event: GenerateEvent) => void;
}

export interface ContentPipeline {
  /**
   * Runs the graph. Resolves with the result; rejects with an
   * {@link AiProviderError} (or `AbortError`) when the copy itself could not be
   * produced. Research and image failures are *not* rejections — they are
   * reported as `stage … failed` events and the result is returned without them.
   */
  generate(request: GenerateRequest, options?: GenerateOptions): Promise<GenerateResult>;
}

// ---------------------------------------------------------------------------
// The copilot
// ---------------------------------------------------------------------------

export interface CopilotMessage {
  role: 'user' | 'assistant';
  content: string;
}

export interface CopilotToolContext {
  signal?: AbortSignal;
}

/**
 * A tool the copilot may call. The API supplies the implementations (list
 * channels, generate a post, draft a post, generate an image); the engine only
 * knows their names, descriptions and input schemas.
 */
export interface CopilotTool<Input = unknown, Output = unknown> {
  name: string;
  description: string;
  inputSchema: z.ZodType<Input>;
  /** True for tools that change nothing — the UI shows them differently. */
  readOnly: boolean;
  execute(input: Input, context: CopilotToolContext): Promise<Output>;
  /**
   * The one-line `summary` for a successful `tool_result` event ("Found 3
   * channels"). Optional: the engine derives one from the tool's name when
   * absent.
   */
  summarize?(output: Output): string;
}

/** What the model may know about the workspace before the conversation starts. */
export interface CopilotContext {
  workspaceName: string;
  /** ISO date (`2026-10-13`), so "tomorrow" means something. */
  today: string;
  /** One line per connected channel: "Acme Marketing (LinkedIn, connected)". */
  channelSummary: string;
}

export type CopilotEvent =
  | { type: 'token'; text: string }
  | { type: 'tool_call'; id: string; name: string; input: unknown }
  | {
      type: 'tool_result';
      id: string;
      name: string;
      ok: boolean;
      output: unknown;
      /** A one-line description for the UI ("Found 3 channels"). */
      summary: string;
    }
  | { type: 'done'; message: string; toolCalls: number };

export interface CopilotRunOptions {
  signal?: AbortSignal;
  onEvent?: (event: CopilotEvent) => void;
}

export interface CopilotRunResult {
  /** The assistant's final reply, in full. */
  message: string;
  toolCalls: number;
}

export interface CopilotAgent {
  /**
   * Answers the last user message in `messages`, calling tools as needed.
   * Stateless: the caller holds the history. Rejects with an
   * {@link AiProviderError} or `AbortError`.
   */
  run(messages: CopilotMessage[], options?: CopilotRunOptions): Promise<CopilotRunResult>;
}

