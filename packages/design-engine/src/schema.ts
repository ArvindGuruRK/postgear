/**
 * The document schema: the boundary between what a browser sends and what the
 * database stores.
 *
 * Every object is `.strict()`. That is the whole security argument for storing
 * a design as JSON: a client can send text, a list, a media id, a nudge, a
 * size step, an alignment and a colour, and *nothing else*. There is no place
 * to put a style, a class, a URL or a script, so there is nothing for the
 * renderer to be tricked into drawing. The slot ids are an enum, the colour
 * roles are an enum, a theme is one the library has, and a hex is a hex.
 *
 * Past the shape, the schema holds each element to what its slot allows: no
 * text on a picture, no size step on a slot without one, no logo placement a
 * layout did not draw room for. A nudge is the one value it corrects rather
 * than refuses, clamping it to the element's region, so the stored document
 * never holds a position the renderer would move.
 *
 * ## Versions
 *
 * `schemaVersion` exists from the first row, before any real document was
 * saved, because adding one later means guessing what the rows without it
 * were. `upgrade()` is the only way a document moves forward: it takes
 * whatever version came out of the database and returns the current shape, or
 * fails loudly. A layout's own version is separate and lives in `layoutId`
 * ("split-picture@1"), so a layout can change without every document moving.
 */
import { z } from 'zod';
import { isArtId } from './art';
import { isHexColor, normalizeHex } from './color';
import { clampToRegion } from './constraints';
import { FORMAT_IDS } from './formats';
import { findLayout, slotPlacement } from './layouts';
import { isThemeId } from './themes';
import {
  COLOR_ROLES,
  DESIGN_SCHEMA_VERSION,
  type DesignDocument,
  type DesignSlide,
  LOGO_PLACEMENTS,
  MAX_BRAND_NAME_LENGTH,
  MAX_CAPTION_LENGTH,
  MAX_HANDLE_LENGTH,
  MAX_LIST_ITEMS,
  MAX_SLIDES,
  MAX_TEXT_LENGTH,
  SLOT_IDS,
} from './types';
import { isKnownFont } from './typography';

const hex = z
  .string()
  .trim()
  .refine(isHexColor, 'Enter a colour like #1A2B3C.')
  .transform((value) => normalizeHex(value) as string);

const colorRole = z.enum(COLOR_ROLES);
const slotId = z.enum(SLOT_IDS);
const format = z.enum(FORMAT_IDS);
const logoPlacement = z.enum(LOGO_PLACEMENTS);

/**
 * Ids are generated by the client (a slide has to exist before it is saved),
 * so they are checked for shape rather than trusted: a long id would bloat
 * every row, and a non-printable one would end up in a DOM attribute.
 */
const clientId = z
  .string()
  .min(1)
  .max(64)
  .regex(/^[A-Za-z0-9_-]+$/, 'An id may only hold letters, numbers, dashes and underscores.');

/**
 * A reference to a row in this workspace: a media id, a brand kit id.
 *
 * Checked for shape, not for being a UUID. Prisma writes UUIDs, but the seeds
 * use readable fixed ids (`seed-brand-kit-lotus`), and the real guard is not
 * the format: the studio service looks every one of these up scoped to the
 * workspace before it is used, so an id that exists elsewhere is a 404 here.
 * The pattern is what keeps a path, a URL or a quote out of the document.
 */
const rowId = z
  .string()
  .min(1)
  .max(64)
  .regex(/^[A-Za-z0-9_-]+$/, 'That is not an id PostGear wrote.');

/**
 * Control characters other than the tab and the newline. Stripped rather than
 * refused: a person pasting from a word processor should get their words,
 * not an error.
 */
// biome-ignore lint/suspicious/noControlCharactersInRegex: stripping them is the point.
const CONTROL_CHARACTERS = /[\u0000-\u0008\u000B\u000C\u000E-\u001F\u007F]/g;

/** Windows and old Mac line endings become one newline, then the rest is cleaned. */
function clean(value: string): string {
  return value.replace(/\r\n?/g, '\n').replace(CONTROL_CHARACTERS, '');
}

/** Slide text. A newline survives, because a headline may genuinely have two lines. */
const plainText = z.string().max(MAX_TEXT_LENGTH).transform(clean);

/** One line: a handle, a brand name. A line break becomes a space. */
function oneLine(max: number) {
  return z
    .string()
    .max(max)
    .transform((value) => clean(value).replace(/\s*\n+\s*/g, ' '));
}

export const brandColorsSchema = z
  .object({
    primary: hex,
    secondary: hex,
    accent: hex,
    background: hex,
    text: hex,
  })
  .strict();

/**
 * A family the library ships. Refused rather than dropped, like a theme: a
 * font id is only ever written by a font picker, so an unknown one is a stale
 * client or a forged request, not a typo to forgive.
 */
export const fontIdSchema = z
  .string()
  .max(64)
  .refine(isKnownFont, 'That font is not one PostGear offers.');

/** A design's or a brand kit's choice of faces. Null keeps the one beneath it. */
export const designFontsSchema = z
  .object({
    heading: fontIdSchema.nullable(),
    body: fontIdSchema.nullable(),
  })
  .strict();

export const elementStateSchema = z
  .object({
    text: plainText.optional(),
    items: z.array(plainText).max(MAX_LIST_ITEMS).optional(),
    mediaId: rowId.nullable().optional(),
    hidden: z.boolean().optional(),
    offset: z
      .object({
        // The clamp below is what really bounds these; the range here only
        // refuses a number that could not be a percentage of anything.
        x: z.number().finite().min(-200).max(200),
        y: z.number().finite().min(-200).max(200),
      })
      .strict()
      .optional(),
    size: z.enum(['sm', 'md', 'lg']).optional(),
    align: z.enum(['start', 'center', 'end']).optional(),
    colorRole: colorRole.optional(),
    color: hex.optional(),
    font: fontIdSchema.optional(),
    placement: logoPlacement.optional(),
  })
  .strict();

export const slideBackgroundSchema = z.discriminatedUnion('kind', [
  z.object({ kind: z.literal('role'), role: colorRole }).strict(),
  z.object({ kind: z.literal('color'), hex }).strict(),
  z
    .object({
      kind: z.literal('media'),
      mediaId: rowId,
      /** 0 is the bare photo, 1 is the tint's own colour. The slider offers 0 to 0.8. */
      overlay: z.number().finite().min(0).max(1),
      /** Black under light ink, or white under dark ink. Absent is the dark tint. */
      tint: z.enum(['dark', 'light']).optional(),
    })
    .strict(),
]);

export const designSlideSchema = z
  .object({
    id: clientId,
    /** Refused here rather than at render time: an unknown layout has no shape. */
    layoutId: z
      .string()
      .max(80)
      .refine((key) => findLayout(key) !== null, {
        message: 'That slide layout is not one PostGear offers.',
      }),
    background: slideBackgroundSchema,
    elements: z.record(slotId, elementStateSchema),
    origin: z
      .number()
      .int()
      .min(0)
      .max(MAX_SLIDES - 1)
      .optional(),
  })
  .strict()
  .superRefine((slide, context) => {
    const layout = findLayout(slide.layoutId);
    if (!layout) return;

    const issue = (path: Array<string | number>, message: string) =>
      context.addIssue({ code: z.ZodIssueCode.custom, path: ['elements', ...path], message });

    for (const [id, state] of Object.entries(slide.elements)) {
      const slot = layout.slots.find((entry) => entry.id === id);

      if (!slot) {
        issue([id], 'That slide layout has no such element.');
        continue;
      }

      if (!state) continue;

      // A list's items belong to a list slot and a picture's id to a picture
      // slot. Without this, a client could park arbitrary values on a slot
      // the renderer reads differently.
      if (state.text !== undefined && slot.kind !== 'text') {
        issue([id, 'text'], 'That element does not hold text.');
      }
      if (state.text !== undefined && slot.bind) {
        issue([id, 'text'], 'That text belongs to the whole design, not to one slide.');
      }
      if (state.items !== undefined && slot.kind !== 'list') {
        issue([id, 'items'], 'That element is not a list.');
      }
      if (state.items && slot.maxItems !== undefined && state.items.length > slot.maxItems) {
        issue([id, 'items'], `That list holds up to ${slot.maxItems} items.`);
      }
      if (state.mediaId !== undefined && slot.kind !== 'image' && slot.kind !== 'logo') {
        issue([id, 'mediaId'], 'That element does not hold a picture.');
      }
      if (state.hidden === true && !slot.optional) {
        issue([id, 'hidden'], 'That element is part of the layout and cannot be hidden.');
      }
      if (state.size !== undefined && !slot.resizable) {
        issue([id, 'size'], 'That element has one size.');
      }
      if (state.align !== undefined && !slot.alignable) {
        issue([id, 'align'], 'That element has one alignment.');
      }
      if ((state.colorRole !== undefined || state.color !== undefined) && !slot.colorable) {
        issue([id, 'color'], 'That element has the colour its layout gives it.');
      }
      if (state.font !== undefined && slot.kind !== 'text' && slot.kind !== 'list') {
        issue([id, 'font'], 'That element has no text to set in a font.');
      }
      if (state.placement !== undefined && !slot.spots?.[state.placement]) {
        issue([id, 'placement'], 'That layout does not offer the logo in that place.');
      }
    }
  })
  .transform((slide): DesignSlide => {
    const layout = findLayout(slide.layoutId);
    if (!layout) return slide;

    const elements: DesignSlide['elements'] = {};

    for (const [id, state] of Object.entries(slide.elements) as Array<
      [keyof DesignSlide['elements'], DesignSlide['elements'][keyof DesignSlide['elements']]]
    >) {
      if (!state) continue;

      const slot = layout.slots.find((entry) => entry.id === id);
      elements[id] =
        slot && state.offset
          ? { ...state, offset: clampToRegion(slotPlacement(slot, state).box, state.offset) }
          : state;
    }

    return { ...slide, elements };
  });

export const designBrandSchema = z
  .object({
    kitId: rowId.nullable(),
    colors: brandColorsSchema.nullable(),
    logoMediaId: rowId.nullable(),
    name: oneLine(MAX_BRAND_NAME_LENGTH).nullable(),
    /** The kit's `updatedAt`, as an ISO timestamp. */
    kitVersion: z.string().datetime().nullable(),
    fonts: designFontsSchema.nullable(),
  })
  .strict();

export const designDocumentSchema = z
  .object({
    schemaVersion: z.literal(DESIGN_SCHEMA_VERSION),
    format,
    /** The preset it came from. Kept, not checked against the library: a retired preset still names its past. */
    presetId: z
      .string()
      .min(1)
      .max(80)
      .regex(/^[a-z0-9-]+$/, 'That is not a template id.'),
    themeId: z.string().refine(isThemeId, 'That theme is not one PostGear offers.'),
    /** Held to the library like the theme: a design names art PostGear draws, or none. */
    art: z
      .string()
      .max(64)
      .refine(isArtId, 'That background art is not one PostGear offers.')
      .nullable(),
    fonts: designFontsSchema.nullable(),
    brand: designBrandSchema,
    handle: oneLine(MAX_HANDLE_LENGTH).default(''),
    caption: z.string().max(MAX_CAPTION_LENGTH).transform(clean),
    slides: z.array(designSlideSchema).min(1).max(MAX_SLIDES),
  })
  .strict()
  .superRefine((document, context) => {
    const ids = new Set<string>();

    for (const [index, slide] of document.slides.entries()) {
      if (ids.has(slide.id)) {
        context.addIssue({
          code: z.ZodIssueCode.custom,
          path: ['slides', index, 'id'],
          message: 'Two slides have the same id.',
        });
      }
      ids.add(slide.id);

      const layout = findLayout(slide.layoutId);
      if (layout && !layout.formats.includes(document.format)) {
        context.addIssue({
          code: z.ZodIssueCode.custom,
          path: ['slides', index, 'layoutId'],
          message: 'That slide layout does not support this format.',
        });
      }
    }
  });

/**
 * Parses a document that came out of the database, upgrading it first.
 *
 * Reads and writes both go through this, so a row written before a schema
 * change is migrated on the way out, and the one written back is current.
 * A row that cannot be upgraded throws: silently rendering half a document
 * would be worse than an error that names the version.
 */
export function parseDesignDocument(value: unknown): DesignDocument {
  return designDocumentSchema.parse(upgrade(value));
}

export function safeParseDesignDocument(
  value: unknown,
): { ok: true; document: DesignDocument } | { ok: false; error: z.ZodError | Error } {
  try {
    const result = designDocumentSchema.safeParse(upgrade(value));
    return result.success
      ? { ok: true, document: result.data }
      : { ok: false, error: result.error };
  } catch (error) {
    return { ok: false, error: error instanceof Error ? error : new Error('Unreadable design') };
  }
}

export class DesignVersionError extends Error {
  constructor(public readonly version: unknown) {
    super(
      typeof version === 'number' && version < DESIGN_SCHEMA_VERSION
        ? `This design was saved in an older format (schema ${version}) with no upgrade step to the current one.`
        : `This design was saved by a newer version of PostGear (schema ${String(version)}).`,
    );
    this.name = 'DesignVersionError';
  }
}

type UpgradeStep = (document: Record<string, unknown>) => Record<string, unknown>;

/**
 * One entry per version, taking the shape at N and returning the shape at
 * N+1. A step is written against the stored shape, never against today's
 * types, and once released it never changes: a row saved at version 1 is
 * moved forward the same way however many versions later it is read.
 */
const UPGRADE_STEPS: Record<number, UpgradeStep> = {
  // 2 added the background art, the design's fonts and the brand kit's
  // fonts. A design saved before had none of them, which is exactly null.
  // A brand that is not an object is left for the schema to refuse.
  1: (document) => ({
    ...document,
    schemaVersion: 2,
    art: null,
    fonts: null,
    brand: isRecord(document.brand) ? { ...document.brand, fonts: null } : document.brand,
  }),
};

function isRecord(value: unknown): value is Record<string, unknown> {
  return typeof value === 'object' && value !== null && !Array.isArray(value);
}

/** Moves a stored document up to the current schema, one version at a time. */
export function upgrade(value: unknown): unknown {
  if (typeof value !== 'object' || value === null) return value;

  let document = { ...(value as Record<string, unknown>) };
  let version = document.schemaVersion;

  // A document written before `schemaVersion` existed cannot exist: the
  // column was created with it. Anything without one is not ours.
  if (typeof version !== 'number') return value;

  if (version > DESIGN_SCHEMA_VERSION) throw new DesignVersionError(version);

  while (version < DESIGN_SCHEMA_VERSION) {
    const step = Object.hasOwn(UPGRADE_STEPS, version) ? UPGRADE_STEPS[version] : undefined;
    if (!step) throw new DesignVersionError(version);

    document = step(document);
    version += 1;
  }

  return document;
}
