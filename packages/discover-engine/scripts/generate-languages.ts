/**
 * Writes `src/geo/languages.generated.ts` from CLDR's `territoryInfo.json`: per
 * country, the languages that are official, official in a region, or spoken by at
 * least 5 percent, ordered by share of the population.
 *
 * `cldr-core` is a build-time dependency only. Nothing at runtime reads it, so the
 * API carries a small table instead of a large package. Re-run after upgrading it:
 *
 *   npm run languages --workspace=@postgear/discover-engine
 */
import { readFileSync, writeFileSync } from 'node:fs';
import { join } from 'node:path';

const MIN_SHARE_PERCENT = 5;
const OFFICIAL = new Set(['official', 'de_facto_official', 'official_regional']);

interface LanguagePopulation {
  _populationPercent?: string;
  _officialStatus?: string;
}

interface TerritoryFile {
  supplemental: {
    version: { _cldrVersion: string; _unicodeVersion: string };
    territoryInfo: Record<string, { languagePopulation?: Record<string, LanguagePopulation> }>;
  };
}

const source = require.resolve('cldr-core/supplemental/territoryInfo.json');
const { supplemental } = JSON.parse(readFileSync(source, 'utf8')) as TerritoryFile;

/** `zh_Hant` to `zh-Hant`. A script variant goes when its plain language is listed too. */
function languagesOf(populations: Record<string, LanguagePopulation>): string[] {
  const kept = Object.entries(populations)
    .map(([tag, info]) => ({
      tag: tag.replace(/_/g, '-'),
      share: Number(info._populationPercent ?? '0'),
      official: OFFICIAL.has(info._officialStatus ?? ''),
    }))
    .filter((entry) => entry.official || entry.share >= MIN_SHARE_PERCENT)
    .sort((a, b) => b.share - a.share || a.tag.localeCompare(b.tag));

  const tags = new Set(kept.map((entry) => entry.tag));
  return kept
    .map((entry) => entry.tag)
    .filter((tag) => !tag.includes('-') || !tags.has(tag.split('-')[0]));
}

const rows = Object.entries(supplemental.territoryInfo)
  .filter(([code]) => /^[A-Z]{2}$/.test(code))
  .map(([code, info]) => [code, languagesOf(info.languagePopulation ?? {})] as const)
  .filter(([, languages]) => languages.length > 0)
  .sort(([a], [b]) => a.localeCompare(b));

const lines = [
  '/**',
  ' * Generated by scripts/generate-languages.ts from cldr-core.',
  ` * CLDR ${supplemental.version._cldrVersion}, Unicode ${supplemental.version._unicodeVersion}. Do not edit by hand.`,
  ' */',
  '',
  `export const CLDR_VERSION = '${supplemental.version._cldrVersion}';`,
  '',
  'export const COUNTRY_LANGUAGES: Readonly<Record<string, readonly string[]>> = {',
  ...rows.map(
    ([code, languages]) =>
      `  ${code}: [${languages.map((language) => `'${language}'`).join(', ')}],`,
  ),
  '};',
  '',
];

const target = join(__dirname, '..', 'src', 'geo', 'languages.generated.ts');
writeFileSync(target, lines.join('\n'));
console.log(`Wrote ${rows.length} countries to ${target}`);
